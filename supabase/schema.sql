-- HalalBridge Internal Admin System — Supabase schema
-- Run this file in Supabase SQL Editor after creating a project.
-- Public website visitors can INSERT laboratory requests only.
-- Only users explicitly assigned role='admin' can read or update requests.

create table if not exists public.admin_profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  role text not null default 'staff' check (role in ('admin','staff')),
  created_at timestamptz not null default now()
);

create table if not exists public.lab_testing_requests (
  id uuid primary key default gen_random_uuid(),
  request_no bigint generated by default as identity unique,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  name text not null check (char_length(name) between 2 and 160),
  email text not null check (char_length(email) <= 254),
  company text check (company is null or char_length(company) <= 200),
  phone text check (phone is null or char_length(phone) <= 60),
  product_name text check (product_name is null or char_length(product_name) <= 200),
  preferred_city text check (preferred_city is null or char_length(preferred_city) <= 120),
  preferred_laboratory text not null check (char_length(preferred_laboratory) between 2 and 240),
  required_test text not null check (char_length(required_test) between 2 and 500),
  department text not null default 'Laboratory Testing' check (department = 'Laboratory Testing'),
  service text,
  standard text,
  message text not null check (char_length(message) between 2 and 5000),
  status text not null default 'Pending' check (status in ('Pending','Under Review','In Process','Completed','Rejected')),
  internal_notes text,
  constraint internal_notes_length check (internal_notes is null or char_length(internal_notes) <= 10000)
);

create index if not exists lab_testing_requests_created_at_idx
  on public.lab_testing_requests (created_at desc);
create index if not exists lab_testing_requests_status_idx
  on public.lab_testing_requests (status);
create index if not exists lab_testing_requests_email_idx
  on public.lab_testing_requests (email);

create or replace function public.is_halalbridge_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.admin_profiles p
    where p.id = (select auth.uid()) and p.role = 'admin'
  );
$$;

alter table public.admin_profiles enable row level security;
alter table public.lab_testing_requests enable row level security;

drop policy if exists "Admins can read own profile" on public.admin_profiles;
create policy "Admins can read own profile"
  on public.admin_profiles for select
  to authenticated
  using (id = (select auth.uid()));

drop policy if exists "Public can submit lab requests" on public.lab_testing_requests;
create policy "Public can submit lab requests"
  on public.lab_testing_requests for insert
  to anon, authenticated
  with check (
    status = 'Pending'
    and internal_notes is null
    and department = 'Laboratory Testing'
  );

drop policy if exists "Admins can read all lab requests" on public.lab_testing_requests;
create policy "Admins can read all lab requests"
  on public.lab_testing_requests for select
  to authenticated
  using ((select public.is_halalbridge_admin()));

drop policy if exists "Admins can update lab requests" on public.lab_testing_requests;
create policy "Admins can update lab requests"
  on public.lab_testing_requests for update
  to authenticated
  using ((select public.is_halalbridge_admin()))
  with check ((select public.is_halalbridge_admin()));

grant select on public.admin_profiles to authenticated;
grant insert on public.lab_testing_requests to anon, authenticated;
grant select, update on public.lab_testing_requests to authenticated;
grant usage, select on sequence public.lab_testing_requests_request_no_seq to anon, authenticated;

